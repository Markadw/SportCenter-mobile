import { act, renderHook, waitFor } from "@testing-library/react-native";
import { profileApi } from "../src/api/profileApi";
import { useProfileViewModel } from "../src/features/profile/hooks/useProfileViewModel";
import type { Profile } from "../src/features/profile/types";
jest.mock("../src/api/profileApi", () => ({ profileApi: { get: jest.fn(), update: jest.fn() } }));
const profile: Profile = { nombre: "Ana", aPaterno: "López", aMaterno: "García", email: "ana@example.com", telefono: "5512345678" };
const get = jest.mocked(profileApi.get), update = jest.mocked(profileApi.update);
beforeEach(() => { get.mockResolvedValue(profile); update.mockResolvedValue(profile); });

test("renovar el token de la misma sesión conserva el draft sin recargar el perfil", async () => {
  let token = "old-token";
  const { result, rerender } = await renderHook(() => useProfileViewModel(token, "stable-session"));
  await waitFor(() => expect(result.current.form).not.toBeNull());
  await act(() => result.current.change("nombre", "Mi edición"));
  const firstSignal = get.mock.calls[0][1]!;
  token = "new-token"; await rerender({});
  expect(result.current.form?.nombre).toBe("Mi edición");
  expect(get).toHaveBeenCalledTimes(1);
  expect(firstSignal.aborted).toBe(false);
  await act(() => result.current.submit());
  expect(update).toHaveBeenCalledWith("new-token", expect.objectContaining({ nombre: "Mi edición" }), expect.any(AbortSignal));
});
test("renovar la sesión no cancela el PATCH y aplica sus valores normalizados al recibir la respuesta", async () => {
  let token = "old-token", finish!: (value: Profile) => void;
  update.mockReturnValueOnce(new Promise(resolve => { finish = resolve; }));
  const { result, rerender } = await renderHook(() => useProfileViewModel(token, "patch-session"));
  await waitFor(() => expect(result.current.form).not.toBeNull());
  await act(() => result.current.change("nombre", " Ana editada "));
  await act(() => { result.current.submit(); result.current.submit(); });
  const signal = update.mock.calls[0][2]!;
  expect(update).toHaveBeenCalledTimes(1); expect(result.current.pending).toBe(true);
  token = "refreshed-token"; await rerender({});
  expect(signal.aborted).toBe(false); expect(result.current.pending).toBe(true);
  await act(() => finish({ ...profile, nombre: "Ana editada" }));
  expect(result.current.saved).toBe(true);
  expect(result.current.form?.nombre).toBe("Ana editada");
  expect(result.current.pending).toBe(false);
  await act(() => result.current.change("telefono", "5598765432"));
  await act(() => result.current.submit());
  expect(update).toHaveBeenLastCalledWith("refreshed-token", expect.objectContaining({ telefono: "5598765432" }), expect.any(AbortSignal));
});
test("cambiar de cuenta cancela la mutación anterior y no aplica una respuesta tardía", async () => {
  let token = "a-token", session = "a-session", finish!: (value: Profile) => void;
  const second = { ...profile, nombre: "Beatriz", email: "beatriz@example.com" };
  get.mockResolvedValueOnce(profile).mockResolvedValueOnce(second);
  update.mockReturnValueOnce(new Promise(resolve => { finish = resolve; }));
  const { result, rerender } = await renderHook(() => useProfileViewModel(token, session));
  await waitFor(() => expect(result.current.form?.nombre).toBe("Ana"));
  await act(() => result.current.change("nombre", "Edición privada A"));
  await act(() => result.current.submit());
  const signal = update.mock.calls[0][2]!;
  token = "b-token"; session = "b-session"; await rerender({});
  expect(signal.aborted).toBe(true);
  await waitFor(() => expect(result.current.form?.nombre).toBe("Beatriz"));
  await act(() => finish({ ...profile, nombre: "Respuesta tardía A" }));
  expect(result.current.form?.email).toBe("beatriz@example.com");
  expect(result.current.form?.nombre).toBe("Beatriz");
  expect(result.current.saved).toBe(false);
  expect(result.current.pending).toBe(false);
});
test("draft y validaciones no reaparecen en otra sesión aunque el loader reutilice el mismo objeto", async () => {
  let session = "one", token = "one-token";
  const { result, rerender } = await renderHook(() => useProfileViewModel(token, session));
  await waitFor(() => expect(result.current.form).not.toBeNull());
  await act(() => result.current.change("telefono", "123"));
  await act(() => result.current.submit());
  expect(result.current.errors.telefono).toBeTruthy();
  session = "two"; token = "two-token"; await rerender({});
  await waitFor(() => expect(result.current.form).not.toBeNull());
  expect(result.current.form?.telefono).toBe(profile.telefono);
  expect(result.current.errors).toEqual({});
});
test("sin sessionId mantiene compatibilidad y trata tokens distintos como alcances distintos", async () => {
  let token = "legacy-one";
  const { result, rerender } = await renderHook(() => useProfileViewModel(token));
  await waitFor(() => expect(result.current.form).not.toBeNull());
  await act(() => result.current.change("nombre", "Draft anterior"));
  token = "legacy-two"; await rerender({});
  await waitFor(() => expect(result.current.form?.nombre).toBe("Ana"));
  expect(get).toHaveBeenCalledTimes(2);
});
test("desmontar cancela una actualización y ninguna respuesta posterior confirma guardado", async () => {
  update.mockImplementationOnce(() => new Promise(() => {}));
  const { result, unmount } = await renderHook(() => useProfileViewModel("token", "unmount-session"));
  await waitFor(() => expect(result.current.form).not.toBeNull());
  await act(() => result.current.submit());
  const signal = update.mock.calls[0][2]!;
  await unmount(); expect(signal.aborted).toBe(true);
});
